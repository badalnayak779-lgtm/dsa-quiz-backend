// GENERATE QUIZ ENDPOINT
// ============================================================

app.post("/api/generate-quiz", async (req, res) => {
  try {
    const { userId, subjects, difficulty } = req.body;

    // Validation
    if (typeof userId !== "string" || userId.length < 3 || userId.length > 100) {
      return res.status(400).json({ error: "Invalid userId." });
    }

    if (!Array.isArray(subjects) || subjects.length === 0) {
      return res.status(400).json({ error: "At least one subject is required." });
    }

    const allowedSubjects = ["DSA", "DBMS", "C++"];
    const cleanSubjects = subjects.filter((s) => allowedSubjects.includes(s));

    if (cleanSubjects.length === 0) {
      return res.status(400).json({ error: "Invalid subjects." });
    }

    const allowedDifficulties = ["easy", "medium", "hard"];
    if (!allowedDifficulties.includes(difficulty)) {
      return res.status(400).json({ error: "Invalid difficulty." });
    }

    ensureUser(userId);
    const previousQuestions = getPreviousQuestions(userId);

    let questions = [];
    let attempts = 0;

    while (questions.length < 5 && attempts < 3) {
      attempts++;

      const generated = await generateQuestions({
        subjects: cleanSubjects,
        difficulty,
        previousQuestions: [
          ...previousQuestions,
          ...questions.map((q) => q.question)
        ],
      });

      for (const question of generated) {
        const hash = hashQuestion(question.question);
        const duplicateInDatabase = questionAlreadyExists(userId, hash);
        const duplicateInCurrentQuiz = questions.some(
          (q) => hashQuestion(q.question) === hash
        );

        if (!duplicateInDatabase && !duplicateInCurrentQuiz) {
          questions.push(question);
        }

        if (questions.length === 5) break;
      }
    }

    if (questions.length < 5) {
      return res.status(500).json({
        error: "Could not generate 5 unique questions. Please try again.",
      });
    }

    saveQuestions({ userId, questions, difficulty });

    const responseQuestions = questions.map((question, index) => ({
      id: Date.now() + index,
      subject: question.subject,
      question: question.question,
      options: question.options,
      correctAnswer: question.correctAnswer,
      explanation: question.explanation,
    }));

    res.json({ questions: responseQuestions });
  } catch (error) {
    console.error("Generate quiz error:", error);
    res.status(500).json({
      error: "Something went wrong while generating the quiz.",
    });
  }
});


// ============================================================
// HISTORY ENDPOINT
// ============================================================

app.get("/api/history/:userId", (req, res) => {
  try {
    const userId = req.params.userId;

    const rows = db
      .prepare(`
        SELECT
          id,
          subject,
          difficulty,
          question,
          options,
          correct_answer,
          explanation,
          created_at
        FROM questions
        WHERE user_id = ?
        ORDER BY created_at DESC
        LIMIT 200
      `)
      .all(userId);

    const questions = rows.map((row) => ({
      id: row.id,
      subject: row.subject,
      difficulty: row.difficulty,
      question: row.question,
      options: JSON.parse(row.options),
      correctAnswer: row.correct_answer,
      explanation: row.explanation,
      createdAt: row.created_at,
    }));

    res.json({ questions });
  } catch (error) {
    console.error("History error:", error);
    res.status(500).json({ error: "Could not load history." });
  }
});


