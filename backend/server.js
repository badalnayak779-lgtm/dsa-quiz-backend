// GENERATE QUIZ ENDPOINT
// ============================================================

app.post("/api/generate-quiz", async (req, res) => {
  try {
    const {
      userId,
      subjects,
      difficulty,
    } = req.body;

    // ========================================================
    // VALIDATE USER ID
    // ========================================================

    if (
      typeof userId !== "string" ||
      userId.length < 3 ||
      userId.length > 100
    ) {
      return res.status(400).json({
        error: "Invalid userId.",
      });
    }

    // ========================================================
    // VALIDATE SUBJECTS
    // ========================================================

    if (
      !Array.isArray(subjects) ||
      subjects.length === 0
    ) {
      return res.status(400).json({
        error: "At least one subject is required.",
      });
    }

    const allowedSubjects = [
      "DSA",
      "DBMS",
      "C++",
    ];

    const cleanSubjects = subjects.filter((s) =>
      allowedSubjects.includes(s)
    );

    if (cleanSubjects.length === 0) {
      return res.status(400).json({
        error: "Invalid subjects.",
      });
    }

    // ========================================================
    // VALIDATE DIFFICULTY
    // ========================================================

    const allowedDifficulties = [
      "easy",
      "medium",
      "hard",
    ];

    if (!allowedDifficulties.includes(difficulty)) {
      return res.status(400).json({
        error: "Invalid difficulty.",
      });
    }

    // ========================================================
    // ENSURE USER EXISTS
    // ========================================================

    ensureUser(userId);

    // ========================================================
    // GET PREVIOUS QUESTIONS
    // ========================================================

    const previousQuestions =
      getPreviousQuestions(userId);

    // ========================================================
    // GENERATE 5 UNIQUE QUESTIONS
    // ========================================================

    let questions = [];
    let attempts = 0;

    while (
      questions.length < 5 &&
      attempts < 3
    ) {
      attempts++;

      const generated =
        await generateQuestions({
          subjects: cleanSubjects,
          difficulty,
          previousQuestions: [
            ...previousQuestions,
            ...questions.map(
              (q) => q.question
            ),
          ],
        });

      for (const question of generated) {
        const hash = hashQuestion(
          question.question
        );

        const duplicateInDatabase =
          questionAlreadyExists(
            userId,
            hash
          );

        const duplicateInCurrentQuiz =
          questions.some(
            (q) =>
              hashQuestion(q.question) ===
              hash
          );

        if (
          !duplicateInDatabase &&
          !duplicateInCurrentQuiz
        ) {
          questions.push(question);
        }

        if (questions.length === 5) {
          break;
        }
      }
    }

    // ========================================================
    // MAKE SURE WE HAVE 5 QUESTIONS
    // ========================================================

    if (questions.length < 5) {
      return res.status(500).json({
        error:
          "Could not generate 5 unique questions. Please try again.",
      });
    }

    // ========================================================
    // SAVE QUESTIONS TO DATABASE
    // ========================================================

    console.log(
      "Saving questions:",
      userId,
      questions.length
    );

    saveQuestions({
      userId,
      questions,
      difficulty,
    });

    // ========================================================
    // PREPARE RESPONSE FOR FLUTTER
    // ========================================================

    const responseQuestions =
      questions.map(
        (question, index) => ({
          id: Date.now() + index,
          subject: question.subject,
          question: question.question,
          options: question.options,
          correctAnswer:
            question.correctAnswer,
          explanation:
            question.explanation,
        })
      );

    // ========================================================
    // SEND QUESTIONS TO FLUTTER
    // ========================================================

    res.json({
      questions: responseQuestions,
    });
  } catch (error) {
    console.error(
      "Generate quiz error:",
      error
    );

    res.status(500).json({
      error:
        "Something went wrong while generating the quiz.",
    });
  }
});

