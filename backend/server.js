// HISTORY ENDPOINT
// ============================================================

app.get(
  "/api/history/:userId",
  (req, res) => {
    try {
      const userId =
        req.params.userId;

      const rows = db
        .prepare(`
          SELECT
            id,
            subject,
            difficulty,
            question,
            options,
            correct_answer,
            explanation,
            created_at
          FROM questions
          WHERE user_id = ?
          ORDER BY created_at DESC
          LIMIT 200
        `)
        .all(userId);

      const questions = rows.map(
        (row) => ({
          id: row.id,
          subject: row.subject,
          difficulty: row.difficulty,
          question: row.question,
          options: JSON.parse(
            row.options
          ),
          correctAnswer:
            row.correct_answer,
          explanation:
            row.explanation,
          createdAt:
            row.created_at,
        })
      );

      console.log(
        "History requested:",
        userId,
        "questions:",
        questions.length
      );

      res.json({
        questions,
      });
    } catch (error) {
      console.error(
        "History error:",
        error
      );

      res.status(500).json({
        error:
          "Could not load history.",
      });
    }
  }
);

